function sumar(a, b) {
  return a + b;
}

function restar(a, b) {
  return a - b;
}

function multiplicar(a, b) {
  return a * b;
}

function dividir(a, b) {
  return a / b;
}

console.log("Suma:", sumar(5, 3));
console.log("Resta:", restar(8, 6));
console.log("Multiplicación:", multiplicar(3, 11));
console.log("División:", dividir(30, 5));
